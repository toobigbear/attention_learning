"""
================================================================================
02_self_attention.py
================================================================================
【对应图片】图6 (RJJO0109.JPG)：《Transformer 自注意力机制原理拆解》

【这张图讲了啥】
分两部分：
  上半部分（数据怎么来的）：
      文本"猫 吃 鱼" → 分词器(Tokenizer)得到 Token ID → 查词嵌入表(Embedding)
      得到每个词的向量 E[猫], E[吃], E[鱼]（图中是 1×768 维）
      → 加上位置编码 P[0], P[1], P[2]（让模型知道词的先后顺序）
      → 得到输入矩阵 X (3×768)，三行 = 三个词，每行 768 维。

  中间（核心公式）：
      Q = X·W_Q     （Query 查询：我要找什么？）
      K = X·W_K     （Key   键：我是什么？能被谁匹配？）
      V = X·W_V     （Value 值：我携带的实际信息是什么？）

      Attention(Q,K,V) = softmax( Q·Kᵀ / √d_k ) · V

      翻译成人话：
      ① Q 和每个 K 做点积 → 算出"我和你有几分相关"（打分）
      ② 除以 √d_k → 防止分数太大把 softmax 压成 0/1 两个极端（缩放）
      ③ softmax → 把分数变成"概率"，一行加起来等于 1（归一化成关注权重）
      ④ 用权重 × 每个词的 V → 加权求和 → 融合整句信息的输出向量

  下半部分（手算例子，3×2 小矩阵）：
      图里直接把"投影后的 Q/K/V"写出来了（3×2 矩阵），
      然后一步步算出：分数矩阵 QKᵀ (3×3) → 除以√2 → softmax 权重 → 加权求和 → 输出 Z。

【大白话理解】
自注意力 = 一句话里每个词，都"环顾四周"，看看别的词跟自己有多大关系，
然后按关系亲疏，把别的词的信息"吸收"进自己的向量里。
比如"猫 吃 鱼"里的"吃"，会重点吸收"鱼"（因为是吃的对象），也吸收一点"猫"（因为是吃的动作发出者）。

【本代码做什么】
完全复现图片下半部分的数值例子。运行后，你会看到每一步的矩阵
和图片上一模一样！建议边跑边对照图片。
================================================================================
"""
import numpy as np

np.set_printoptions(precision=3, suppress=True)  # 打印简洁一点


def softmax(x):
    """softmax：把一行分数变成一行概率（和为1）"""
    exp_x = np.exp(x - np.max(x))        # 减最大值是为了数值稳定，不影响结果
    return exp_x / exp_x.sum(axis=-1, keepdims=True)


# ==============================================================================
# 第一步：定义输入（对应图片上半部分 + 下半部分开头的"输入矩阵 X (3x2)"）
# ==============================================================================
print("=" * 78)
print("自注意力完整计算（复现图片 RJJO0109 下半部分的数字例子）")
print("=" * 78)

# 简化例子：每个词只有 2 维（真实世界是 768 维，道理一样）
# 行 = 词，列 = 向量维度
X = np.array([
    [1.0, 0.5],   # 猫
    [0.8, 0.9],   # 吃
    [0.3, 1.2],   # 鱼
])
print("\n【输入矩阵 X (3×2)】三行=三个词，每行=该词的向量")
print(X)

# ==============================================================================
# 第二步：线性投影 Q = X·W_Q, K = X·W_K, V = X·W_V
# ==============================================================================
# 注意：图片为了展示方便，直接把"投影后的 Q/K/V"画了出来。
# 这里我们补上投影这一步（用固定的 W），让你看到"投影"到底干了什么。
# 投影的本质：给每个词发三副"眼镜"——
#   W_Q 眼镜：看出来"我要找什么"（Query）
#   W_K 眼镜：看出来"我是什么标签"（Key）
#   W_V 眼镜：看出来"我的实际内容"（Value）
W_Q = np.array([[0.5, 0.2], [0.1, 0.7]])   # 2×2 投影矩阵（随便挑的）
W_K = np.array([[0.4, 0.1], [0.3, 0.3]])
W_V = np.array([[0.5, 0.9], [0.2, 0.1]])

Q = X @ W_Q
K = X @ W_K
V = X @ W_V

print("\n【投影后】Q = X·W_Q，K = X·W_K，V = X·W_V（每个都是 3×2）")
print("Q (查询: 我要找什么):\n", Q)
print("K (键:   我是什么):\n", K)
print("V (值:   我有什么内容):\n", V)

# 为了让下面的数字和图片完全一致，我们改用图片给定的 Q/K/V（等效于换了一套 W）
print("\n" + "-" * 78)
print("【说明】图片为了手算方便，直接给出投影后的结果。下面改用图片的数字，")
print("       这样后续每一步你都能和图片对得上：")
print("-" * 78)
Q = np.array([
    [0.60, 0.65],   # 猫的 Query
    [0.58, 0.87],   # 吃的 Query   ← 图片标注"重点"的那行
    [0.39, 0.93],   # 鱼的 Query
])
K = np.array([
    [0.72, 0.31],   # 猫的 Key
    [0.68, 0.51],   # 吃的 Key
    [0.24, 0.96],   # 鱼的 Key
])
V = np.array([
    [0.80, 1.20],   # 猫的 Value
    [1.10, 0.90],   # 吃的 Value
    [0.40, 1.80],   # 鱼的 Value
])

# ==============================================================================
# 第三步：算注意力分数 = Q · Kᵀ  （图片：转置与匹配）
# ==============================================================================
# K.T 把 K 转置：K 本来是 3×2（三行=三个词），转置后变成 2×3（三列=三个词）
# 这样 Q 的每一行（一个词）就能和 K 的每一列（一个词）做点积。
# 点积结果大 = 这两个词关系密切（Query 和 Key 匹配上了）。
print("\n【转置】Kᵀ (2×3)：把 K 的列变成行，方便做矩阵乘法")
print(K.T)

scores = Q @ K.T
print("\n【注意力分数矩阵】scores = Q·Kᵀ (3×3)")
print("       猫      吃      鱼")
for i, word in enumerate(["猫", "吃", "鱼"]):
    print(f"{word}: {scores[i]}")

# ==============================================================================
# 第四步：缩放 scores / √d_k   （图片：除以 sqrt(d_k)=1.414）
# ==============================================================================
d_k = Q.shape[1]                     # 每个向量的维度 = 2
scaled = scores / np.sqrt(d_k)       # 为什么除？维度越大点积越大，softmax越容易饱和，
                                     # 除一下让梯度更稳定（Transformer 论文的标配）
print(f"\n【缩放】除以 √d_k = √{d_k} = {np.sqrt(d_k):.3f}")
print("缩放后的分数（以'吃'行演示）:")
print(scaled[1], "  ← 对应图片里 [0.49 0.59 0.69]")

# ==============================================================================
# 第五步：softmax 归一化 → 注意力权重矩阵 A   （图片：Step 4）
# ==============================================================================
A = softmax(scaled)
print("\n【注意力权重矩阵】A = softmax(缩放后分数) (3×3)，每行之和 = 1.0")
for i, word in enumerate(["猫", "吃", "鱼"]):
    print(f"{word}: {A[i]}   行和 = {A[i].sum():.3f}")
print("含义：'吃'这个字，30% 关注'猫'，33% 关注'吃'自己，37% 关注'鱼'")

# ==============================================================================
# 第六步：加权求和 → 输出 Z = A · V   （图片：Step 5）
# ==============================================================================
# 每个词的输出 = 它关注所有词的权重 × 所有词的 V 加起来
Z = A @ V
print("\n【输出矩阵】Z = A·V (3×2)：每个词都吸收了整句的信息")
print("以'吃'为例，手工展开：")
print("  0.30×[0.80,1.20] + 0.33×[1.10,0.90] + 0.37×[0.40,1.80]")
print("  = 0.30×猫的V + 0.33×吃的V + 0.37×鱼的V")
for i, word in enumerate(["猫", "吃", "鱼"]):
    print(f"{word}: {Z[i]}")

print("\n" + "=" * 78)
print("结论：'吃'这个词经过自注意力之后，向量里已经混入了'猫'和'鱼'的信息。")
print("这就是'每个词融合整句信息'的含义。")
print("=" * 78)

# ==============================================================================
# 附赠小实验：看看如果把一句话里的词顺序打乱，注意力会怎样？
# ==============================================================================
print("\n\n【小实验】句子改为'鱼 吃 猫'（把主语宾语对调），分数会怎么变？")
# 注意：词的顺序变了，对应的 Q/K/V 也要跟着换位置（保持"每个词自己的向量"）
Q2 = np.array([[0.39, 0.93], [0.58, 0.87], [0.60, 0.65]])  # 鱼/吃/猫 的 Query
K2 = np.array([[0.24, 0.96], [0.68, 0.51], [0.72, 0.31]])  # 鱼/吃/猫 的 Key
V2 = np.array([[0.40, 1.80], [1.10, 0.90], [0.80, 1.20]])  # 鱼/吃/猫 的 Value
scores2 = Q2 @ K2.T
A2 = softmax(scores2 / np.sqrt(d_k))
print("新权重矩阵：")
for i, word in enumerate(["鱼", "吃", "猫"]):
    print(f"{word}: {A2[i]}")
print("看！'吃'的注意力跟着语义位置变了 —— 注意力机制是靠'向量相关性'打分的，")
print("词换位置后，相关关系也随之改变。这就是注意力'动态'的来源。")
